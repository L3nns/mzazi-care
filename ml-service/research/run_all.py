# -*- coding: utf-8 -*-
"""
Runs every experiment and writes docs/research/RESULTS.md.

    cd backend && npm run benchmark:served      # optional: the live search route (needs MySQL)
    cd ml-service && python -m research.run_all

The tables are generated; nothing in RESULTS.md is typed by hand. The
interpretation lives in docs/research/FINDINGS.md.
"""
from __future__ import annotations

import argparse
import time

from research.common import ROOT, OUT_DIR, environment
from research import search_benchmark, rec_experiments


def main():
    ap = argparse.ArgumentParser(description=__doc__, formatter_class=argparse.RawDescriptionHelpFormatter)
    ap.add_argument("--encoder", default=None, help="recommendation experiments: sbert | tfidf | auto")
    ap.add_argument("--allow-mismatch", action="store_true")
    args = ap.parse_args()

    t0 = time.time()
    search_md, picks = search_benchmark.run(args.allow_mismatch)
    rec_md, rec_info = rec_experiments.run(args.encoder)
    env = environment()
    head = [
        "# Research results",
        "",
        "Generated by `python -m research.run_all` (ml-service/) on "
        f"{time.strftime('%Y-%m-%d %H:%M')} in {time.time() - t0:.0f} s. Do not edit by hand: rerun it. "
        "What the numbers mean, and what they do not, is in [FINDINGS.md](FINDINGS.md).",
        "",
        "Environment: " + ", ".join(f"{k} {v}" for k, v in env.items()) + ". "
        "Bootstrap: 2,000 resamples, seed 7. Raw per-query and per-user values are in "
        f"`{OUT_DIR.relative_to(ROOT).as_posix()}/`.",
        "",
    ]
    out = ROOT / "docs" / "research" / "RESULTS.md"
    out.parent.mkdir(parents=True, exist_ok=True)
    out.write_text("\n".join(head) + "\n" + search_md + "\n" + rec_md, encoding="utf-8")
    print(f"written {out}")


if __name__ == "__main__":
    main()
